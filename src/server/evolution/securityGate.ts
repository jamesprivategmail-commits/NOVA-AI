import path from 'path';
import type { SecurityGateCheck, SecurityRiskCategory } from './types.js';

const PROTECTED_PATTERNS: Array<{
  category: SecurityRiskCategory;
  fileRegex?: RegExp;
  textRegex?: RegExp;
  reason: string;
}> = [
  {
    category: 'auth_change',
    fileRegex: /(auth|login|oauth|AuthScreen|session|admin)/i,
    textRegex: /\b(authentication|login flow|oauth|password|jwt|session cookie|admin role|tier permission)\b/i,
    reason: 'Touches authentication, user permissions, or OAuth identity flow.',
  },
  {
    category: 'database_migration',
    fileRegex: /(firebase|firestore|db\.ts|database|schema|migration)/i,
    textRegex: /\b(firestore rules|database migration|schema change|drop collection|alter table)\b/i,
    reason: 'Modifies database configuration, Firestore rules, or persistence schemas.',
  },
  {
    category: 'security_sensitive',
    fileRegex: /(security|helmet|rateLimit|middleware|createApp\.ts)/i,
    textRegex: /\b(helmet|csp|rate limit|cors|ssrf|sanitizer|xss|security header)\b/i,
    reason: 'Modifies security middleware, HTTP headers, or server request guards.',
  },
  {
    category: 'api_credentials',
    fileRegex: /(\.env|apikey|keys|secrets|telegram\/bot)/i,
    textRegex: /\b(api key|apikey|secret key|bearer token|rotate credentials|TELEGRAM_BOT_TOKEN)\b/i,
    reason: 'Touches API credentials, environment secrets, or token storage.',
  },
  {
    category: 'paid_service',
    fileRegex: /(subscription|billing|wallet|stripe|pricing)/i,
    textRegex: /\b(paid service|billing|stripe|charge|wallet|payment|spend money|paid tier)\b/i,
    reason: 'Involves paid third-party services, billing, or monetary operations.',
  },
  {
    category: 'destructive',
    textRegex: /\b(rm\s+-rf|unlinkSync|rmdirSync|drop database|delete collection|wipe all|force push)\b/i,
    reason: 'Contains potentially destructive file or data deletion operations.',
  },
];

/**
 * Classifies whether proposed file edits or commands require explicit human approval
 * before touching production code, credentials, auth, DB, or paid services.
 */
export function classifySecurityGate(
  targetFiles: string[],
  summaryAndCodeText: string
): SecurityGateCheck {
  const categories = new Set<SecurityRiskCategory>();
  const reasons: string[] = [];

  let touchesProtectedFiles = false;

  for (const file of targetFiles) {
    const normalized = file.replace(/\\/g, '/').replace(/^\/+/, '');
    if (
      normalized.startsWith('src/') ||
      normalized === 'server.ts' ||
      normalized === 'package.json' ||
      normalized === 'firestore.rules' ||
      normalized === 'vite.config.ts' ||
      normalized === 'index.html' ||
      normalized.startsWith('api/')
    ) {
      categories.add('production_deploy');
      touchesProtectedFiles = true;
    }

    for (const rule of PROTECTED_PATTERNS) {
      if (rule.fileRegex && rule.fileRegex.test(normalized)) {
        categories.add(rule.category);
        touchesProtectedFiles = true;
        if (!reasons.includes(rule.reason)) {
          reasons.push(rule.reason);
        }
      }
    }
  }

  for (const rule of PROTECTED_PATTERNS) {
    if (rule.textRegex && rule.textRegex.test(summaryAndCodeText)) {
      categories.add(rule.category);
      if (!reasons.includes(rule.reason)) {
        reasons.push(rule.reason);
      }
    }
  }

  if (categories.has('production_deploy') && reasons.length === 0) {
    reasons.push('Deploys code changes into the live production repository tree (requires operator approval).');
  }

  if (categories.size === 0) {
    categories.add('safe_sandbox');
    reasons.push('Isolated within evolution sandbox; explicit approval still required to promote to production.');
  }

  // Always require explicit human approval before production promotion
  return {
    requiresApproval: true,
    riskCategories: Array.from(categories),
    reasons,
    touchesProtectedFiles,
  };
}

/**
 * Strictly validates that a resolved path remains inside the designated sandbox or repo root
 * to prevent directory traversal attacks (`../` escapes).
 */
export function isInsideSandbox(rootDir: string, candidatePath: string): boolean {
  const resolvedRoot = path.resolve(rootDir);
  const resolvedCandidate = path.resolve(rootDir, candidatePath);
  if (resolvedCandidate === resolvedRoot) return false;
  return resolvedCandidate.startsWith(resolvedRoot + path.sep);
}

/**
 * Sanitizes relative repository file paths generated by AI agents.
 */
export function sanitizeRepoRelativePath(rawPath: string): string | null {
  const cleaned = String(rawPath || '')
    .trim()
    .replace(/\\/g, '/')
    .replace(/^\/+/, '');
  if (!cleaned || cleaned.includes('..') || cleaned.includes('\0')) {
    return null;
  }
  return cleaned;
}
